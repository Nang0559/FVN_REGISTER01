namespace FVN_REGISTER.AI.Application.Contracts;

/// <summary>
/// A proposed state-changing business command. The AI may prepare a proposal but cannot
/// authorize it. The host binds the preview to tenant, actor, command hash and expiry.
/// </summary>
public sealed record FvnBusinessCommandPreviewRequest(
    string ToolCode,
    string InputJson,
    string? ConversationId,
    string? CorrelationId);

/// <summary>
/// Preview returned by the trusted FVN host after fresh authorization and domain validation.
/// PreviewToken is opaque, short-lived and must be single-use at commit time.
/// </summary>
public sealed record FvnBusinessCommandPreview(
    string PreviewId,
    string PreviewToken,
    string ToolCode,
    string Summary,
    string ChangeSetJson,
    DateTimeOffset ExpiresAtUtc,
    bool RequiresHumanConfirmation,
    IReadOnlyCollection<FvnBusinessProvenance> Provenance);

/// <summary>
/// Explicit confirmation supplied by the human-facing FVN UI, not generated by the model.
/// IdempotencyKey must be stable across retries of the same user-confirmed action.
/// </summary>
public sealed record FvnBusinessCommandConfirmation(
    string PreviewId,
    string PreviewToken,
    string ConfirmationId,
    string IdempotencyKey,
    string? CorrelationId);

public sealed record FvnBusinessCommandExecutionResult(
    string CommandId,
    string Status,
    bool WasReplay,
    string? ResultJson,
    DateTimeOffset CompletedAtUtc,
    IReadOnlyCollection<FvnBusinessProvenance> Provenance);
